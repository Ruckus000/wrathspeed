import Foundation
import WrathspeedCore

/// One model call, recorded at every stage so a miss is attributed to the model, the schema,
/// or the keyword gate — and then to the rule, which says whether the intent could act.
struct RunRecord: Codable {
    var caseID: String
    var family: String
    var fixture: String
    var run: Int
    var message: String
    var rawIntent: String
    var rawFields: [String: String]
    var mappedIntent: IntentName
    var resolvedIntent: IntentName
    var proposal: String
    var reply: String
    var latencyMs: Int
    var pass: Bool
    var failures: [String]
    var flags: [String]
}

enum Scoring {
    static func score(
        _ goldenCase: GoldenCase,
        built: Fixture.Built,
        raw: CoachTypedResponse,
        mapped: CoachIntent,
        resolved: CoachIntent,
        promptText: String,
        isCannedAsk: Bool = false
    ) -> (failures: [String], flags: [String], proposal: String) {
        var failures: [String] = []
        var flags: [String] = []
        let name = IntentName(resolved)

        if !goldenCase.expect.contains(name) {
            failures.append("INTENT expected \(goldenCase.expect.map(\.rawValue).sorted().joined(separator: "|")) got \(name.rawValue)")
        }
        if goldenCase.forbid.contains(name) {
            failures.append("FORBIDDEN \(name.rawValue)")
        }
        if let param = goldenCase.param, let miss = check(param, against: resolved, built: built) {
            failures.append("PARAM \(miss)")
        }
        let reply = raw.reply.lowercased()
        for fragment in goldenCase.mustNotSay where reply.contains(fragment) {
            failures.append("UNSAFE_REPLY contains \"\(fragment)\"")
        }

        // A conversational resolution whose reply still promises an edit: the runner reads a
        // promise and no card ever appears.
        // A canned ask is conditional ("if you want..., say so and I'll preview"); only the model's
        // own text can promise an edit it did not get.
        if IntentName.conversation.contains(name), !isCannedAsk,
           reply.contains("i'll") || reply.contains("i will") || reply.contains("i’ll"),
           ["preview", "adjust", "reshape", "move", "update", "reduce", "change your"].contains(where: reply.contains) {
            flags.append("PROMISE_WITHOUT_PROPOSAL")
        }
        if raw.reply.contains("**") || raw.reply.contains("\n- ") || raw.reply.contains("# ") {
            flags.append("MARKDOWN")
        }
        if raw.reply.count > 600 { flags.append("LONG(\(raw.reply.count))") }
        for number in ungroundedNumbers(in: raw.reply, prompt: CoachPromptBuilder.instructions + promptText) {
            flags.append("UNGROUNDED_NUMBER(\(number))")
        }

        // The rule's verdict on the resolved intent: could this have become an applicable card?
        let proposal: String
        if name == .moveLongRun || name == .retargetVDOT {
            // Regenerated by the store, not previewed by CoachPlanRules; the rule cannot judge these.
            proposal = "store-level"
        } else if IntentName.edits.contains(name) {
            do {
                let result = try CoachPlanRules.preview(
                    intent: resolved, plan: built.plan, profile: built.profile,
                    asOf: Fixture.asOf, calendar: Fixture.calendar
                )
                let blocking = result.warnings.filter { $0.severity == .blocking }
                proposal = blocking.isEmpty ? "applicable" : "blocked: " + blocking.map(\.message).joined(separator: " / ")
            } catch {
                proposal = "error: \(error)"
            }
        } else {
            proposal = "none"
        }
        return (failures, flags, proposal)
    }

    private static func check(_ param: ParamCheck, against intent: CoachIntent, built: Fixture.Built) -> String? {
        let calendar = Fixture.calendar
        switch (param, intent) {
        case let (.travelDays(days), .reshapeForTravel(dates)):
            let got = dates.map { calendar.component(.day, from: $0) }.sorted()
            return got == days ? nil : "travel days \(got) expected \(days)"
        case let (.weekday(weekday), .moveLongRun(to)):
            return to == weekday ? nil : "weekday \(to.displayName) expected \(weekday.displayName)"
        case let (.workoutOn(day), .moveWorkoutIndoors(workoutID)):
            let expected = built.plan.workouts.first {
                calendar.component(.day, from: $0.date) == day
                    && calendar.component(.month, from: $0.date) == 9
                    && $0.blueprint.kind.isRunning
            }
            guard let expected else { return "fixture has no run on Sept \(day)" }
            if expected.id == workoutID { return nil }
            let got = built.plan.workouts.first { $0.id == workoutID }.map { Fixture.dayLabel($0.date) } ?? "unknown"
            return "workout on \(got) expected Sept \(day)"
        case let (.vdot(range), .retargetVDOT(target)):
            return range.contains(target) ? nil : "vdot \(target) expected \(range)"
        default:
            // The intent itself is checked by INTENT; a parameter check on a different intent
            // (an accepted clarification, say) is not a second failure.
            return nil
        }
    }

    /// Numbers in the reply that appear nowhere in what the model was shown. Advisory: a pace
    /// in a reply is invented, because the prompt carries `vdot=` and no pace zones.
    private static func ungroundedNumbers(in reply: String, prompt: String) -> [String] {
        let pattern = try! NSRegularExpression(pattern: #"\b\d+(?:[.,]\d+)?\b"#)
        let range = NSRange(reply.startIndex..., in: reply)
        var out: [String] = []
        for match in pattern.matches(in: reply, range: range) {
            guard let r = Range(match.range, in: reply) else { continue }
            let token = String(reply[r]).replacingOccurrences(of: ",", with: "")
            guard let value = Double(token), value >= 3 else { continue } // small counts are fine
            let grounded = prompt.contains(token)
                || prompt.contains(String(Int(value * 1000)))    // "5 km" against "5000m"
                || prompt.contains(String(Int(value)))
            if !grounded { out.append(token) }
        }
        return Array(Set(out)).sorted()
    }
}

extension Fixture {
    static func dayLabel(_ date: Date) -> String {
        let f = DateFormatter()
        f.calendar = calendar; f.timeZone = calendar.timeZone; f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "EEE MMM d"
        return f.string(from: date)
    }
}
